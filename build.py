#!/usr/bin/env python3
"""Build AnyPS5 GUI with PyInstaller, choosing the target operating system.

Expected layout (everything in the same folder as this script):

  build.py
  AnyPS5_GUI.py
  index.html       <- embedded in the executable (not left as a file)
  Icon/            <- your icons (.ico, .icns, .png)

NOTE: PyInstaller cannot cross-compile. To get the app for an operating
system you must run this script ON that operating system.
"""
import base64
import os
import shutil
import subprocess
import sys
import zlib

ROOT = os.path.dirname(os.path.abspath(__file__))
ICON_DIR = os.path.join(ROOT, "Icon")
MAIN = "AnyPS5_GUI.py"
UI = "index.html"
APP_NAME = "AnyPS5_GUI"
UI_MODULE = os.path.join(ROOT, "_ui_data.py")

TARGETS = {
  "1": ("Windows", "win32", ".ico"),
  "2": ("macOS", "darwin", ".icns"),
  "3": ("Linux", "linux", ".png"),
}


def ask_target():
  print("Which operating system do you want to build the app for?\n")
  for k, (name, _, _) in TARGETS.items():
    print(f"  {k}) {name}")
  print("  q) Quit\n")
  while True:
    c = input("Choice: ").strip().lower()
    if c in ("q", "quit", "exit"):
      sys.exit(0)
    if c in TARGETS:
      return TARGETS[c]
    print("Invalid choice.")


def current_platform():
  p = sys.platform
  if p.startswith("win"):
    return "win32"
  if p == "darwin":
    return "darwin"
  return "linux"


def find_icon(ext):
  """Look in the Icon folder for a file with the requested extension."""
  if not os.path.isdir(ICON_DIR):
    return None
  files = sorted(os.listdir(ICON_DIR))
  for f in files:
    if f.lower().endswith(ext):
      return os.path.join(ICON_DIR, f)
  return None


def convert_icon(ext):
  """If .ico/.icns is missing but there is a PNG, try to convert it with Pillow."""
  png = find_icon(".png")
  if not png:
    return None
  try:
    from PIL import Image
  except ImportError:
    print("Pillow is not installed: trying to install it to convert the icon...")
    subprocess.call([sys.executable, "-m", "pip", "install", "pillow"])
    try:
      from PIL import Image
    except ImportError:
      return None
  out = os.path.join(ICON_DIR, "generated" + ext)
  img = Image.open(png).convert("RGBA")
  if ext == ".ico":
    img.save(out, sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
  elif ext == ".icns":
    img.resize((1024, 1024)).save(out)
  else:
    return None
  print(f"Icon generated from PNG: {out}")
  return out


def embed_ui():
  """Compress index.html and write it to _ui_data.py (imported by the program)."""
  with open(os.path.join(ROOT, UI), "rb") as fh:
    raw = fh.read()
  data = base64.b64encode(zlib.compress(raw, 9)).decode("ascii")
  with open(UI_MODULE, "w", encoding="utf-8") as fh:
    fh.write("# generated by build.py - do not edit\nDATA = (\n")
    for i in range(0, len(data), 100):
      fh.write(f'  "{data[i:i + 100]}"\n')
    fh.write(")\n")


def ensure_pyinstaller():
  try:
    import PyInstaller  # noqa: F401
  except ImportError:
    print("PyInstaller not found, installing it...")
    subprocess.check_call([sys.executable, "-m", "pip", "install", "pyinstaller"])


def main():
  name, plat, ext = ask_target()

  if plat != current_platform():
    print(f"\nWARNING: you are not running on {name}.")
    print("PyInstaller cannot create apps for another operating system.")
    print(f"Run this script on {name} to get the correct build.")
    sys.exit(1)

  for f in (MAIN, UI):
    if not os.path.isfile(os.path.join(ROOT, f)):
      sys.exit(f"Missing file: {f} (it must be next to build.py)")

  icon = find_icon(ext) or (convert_icon(ext) if ext in (".ico", ".icns") else None)
  png = find_icon(".png")
  if not icon:
    print(f"No {ext} icon found in '{ICON_DIR}': building without an icon.")

  debug = input("\nDEBUG build with a visible console (shows errors)? [y/N]: ").strip().lower() in ("y", "yes")

  ensure_pyinstaller()

  cmd = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
         "--name", APP_NAME]
  if plat == "darwin":
    cmd += ["--windowed"]          # creates AnyPS5_GUI.app (in debug, run the binary from Terminal)
  else:
    cmd += ["--console" if debug else "--noconsole", "--onefile"]
  if icon:
    cmd += ["--icon", icon]
  cmd += ["--hidden-import", "_ui_data", "--collect-all", "webview"]
  # window icon at runtime: .ico on Windows, .png elsewhere (macOS ignores it)
  rt_src = icon if plat == "win32" else png
  tmp_icon = None
  if rt_src:
    tmp_icon = os.path.join(ROOT, "icon" + os.path.splitext(rt_src)[1].lower())
    if os.path.abspath(rt_src) != os.path.abspath(tmp_icon):
      shutil.copy2(rt_src, tmp_icon)
    else:
      tmp_icon = None  # already in the right place, do not delete it afterwards
    cmd += ["--add-data", f"{os.path.join(ROOT, 'icon' + os.path.splitext(rt_src)[1].lower())}{os.pathsep}."]
  cmd.append(os.path.join(ROOT, MAIN))

  embed_ui()
  print("\nRunning:", " ".join(cmd), "\n")
  try:
    rc = subprocess.call(cmd, cwd=ROOT)
  finally:
    if os.path.isfile(UI_MODULE):
      os.remove(UI_MODULE)
    if tmp_icon and os.path.isfile(tmp_icon):
      os.remove(tmp_icon)
  if rc != 0:
    sys.exit("Build failed.")

  dist = os.path.join(ROOT, "dist")

  if plat == "linux" and png:
    desktop = os.path.join(dist, APP_NAME + ".desktop")
    with open(desktop, "w", encoding="utf-8") as fh:
      fh.write("[Desktop Entry]\n"
               "Type=Application\n"
               "Name=AnyPS5 GUI\n"
               f"Exec={os.path.join(dist, APP_NAME)}\n"
               f"Icon={png}\n"
               "Terminal=false\n"
               "Categories=Utility;\n")
    os.chmod(desktop, 0o755)
    print(f"Launcher created: {desktop}")

  print(f"\nDone! Build for {name} in: {dist}")


if __name__ == "__main__":
  main()